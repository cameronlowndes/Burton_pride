import ExcelJS from "exceljs";

export type InventoryExcelRow = {
  name: string;
  sku: string;
  barcode?: string | null;
  category?: string | null;
  location?: string | null;
  supplier?: string | null;
  quantity: number;
  reorderLevel: number;
  targetLevel?: number | null;
  unitCost?: number | null;
  salePrice?: number | null;
  stockValue?: number | null;
  status: string;
  updatedAt?: string | null;
  updatedByName?: string | null;
};

type InventoryExcelSummary = {
  totalItems: number;
  totalUnits: number;
  lowStockItems: number;
  outOfStockItems: number;
  totalValue: number;
};

type ExportInventoryWorkbookOptions = {
  items: InventoryExcelRow[];
  summary?: InventoryExcelSummary;
  reportTitle?: string;
  generatedBy?: string | null;
  fileName?: string;
};

const COLOURS = {
  navy: "FF172554",
  blue: "FF2563EB",
  blueLight: "FFDBEAFE",
  purple: "FF7C3AED",
  purpleLight: "FFEDE9FE",
  green: "FF059669",
  greenLight: "FFD1FAE5",
  amber: "FFD97706",
  amberLight: "FFFEF3C7",
  red: "FFDC2626",
  redLight: "FFFEE2E2",
  slate: "FF334155",
  slateLight: "FFF1F5F9",
  white: "FFFFFFFF",
  border: "FFD8DEE9",
  text: "FF111827",
  muted: "FF64748B",
};

function safeNumber(value: number | null | undefined) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

function displayStatus(status: string) {
  const clean = String(status || "").trim().toLowerCase();

  if (clean === "in_stock") return "In stock";
  if (clean === "low_stock") return "Low stock";
  if (clean === "out_of_stock") return "Out of stock";
  if (clean === "archived") return "Archived";

  return status || "Unknown";
}

function statusStyle(status: string) {
  const clean = String(status || "").trim().toLowerCase();

  if (clean === "in_stock") {
    return {
      fill: COLOURS.greenLight,
      font: COLOURS.green,
    };
  }

  if (clean === "low_stock") {
    return {
      fill: COLOURS.amberLight,
      font: COLOURS.amber,
    };
  }

  if (clean === "out_of_stock") {
    return {
      fill: COLOURS.redLight,
      font: COLOURS.red,
    };
  }

  return {
    fill: COLOURS.slateLight,
    font: COLOURS.slate,
  };
}

function formatDateForCell(value?: string | null) {
  if (!value) return null;

  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

function createDownloadName(fileName?: string) {
  if (fileName?.trim()) {
    return fileName.toLowerCase().endsWith(".xlsx")
      ? fileName
      : `${fileName}.xlsx`;
  }

  return `burton-pride-inventory-${new Date()
    .toISOString()
    .slice(0, 10)}.xlsx`;
}

export async function exportInventoryWorkbook({
  items,
  summary,
  reportTitle = "Burton Pride Inventory Report",
  generatedBy,
  fileName,
}: ExportInventoryWorkbookOptions) {
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error("There are no inventory rows to export.");
  }

  const workbook = new ExcelJS.Workbook();

  workbook.creator = generatedBy?.trim() || "Burton Pride Stock Control";
  workbook.lastModifiedBy =
    generatedBy?.trim() || "Burton Pride Stock Control";
  workbook.created = new Date();
  workbook.modified = new Date();
  // workbook.subject does not exist on ExcelJS Workbook; avoid assigning it
  (workbook.properties as any).title = reportTitle;

  const sheet = workbook.addWorksheet("Inventory", {
    views: [
      {
        state: "frozen",
        xSplit: 2,
        ySplit: 7,
        topLeftCell: "C8",
        activeCell: "A8",
      },
    ],
    properties: {
      defaultRowHeight: 20,
    },
    pageSetup: {
      orientation: "landscape",
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
      paperSize: 9,
      margins: {
        left: 0.25,
        right: 0.25,
        top: 0.5,
        bottom: 0.5,
        header: 0.2,
        footer: 0.2,
      },
    },
  });

  sheet.mergeCells("A1:O1");
  const titleCell = sheet.getCell("A1");
  titleCell.value = reportTitle;
  titleCell.font = {
    name: "Aptos Display",
    size: 22,
    bold: true,
    color: { argb: COLOURS.white },
  };
  titleCell.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: COLOURS.navy },
  };
  titleCell.alignment = {
    vertical: "middle",
    horizontal: "left",
  };
  sheet.getRow(1).height = 38;

  sheet.mergeCells("A2:O2");
  const subtitleCell = sheet.getCell("A2");
  subtitleCell.value = `Generated ${new Intl.DateTimeFormat("en-GB", {
    dateStyle: "full",
    timeStyle: "short",
  }).format(new Date())}${
    generatedBy?.trim() ? ` • Generated by ${generatedBy.trim()}` : ""
  }`;
  subtitleCell.font = {
    name: "Aptos",
    size: 10,
    italic: true,
    color: { argb: COLOURS.muted },
  };
  subtitleCell.alignment = {
    vertical: "middle",
    horizontal: "left",
  };
  sheet.getRow(2).height = 24;

  const calculatedSummary: InventoryExcelSummary = summary || {
    totalItems: items.length,
    totalUnits: items.reduce(
      (total, item) => total + safeNumber(item.quantity),
      0,
    ),
    lowStockItems: items.filter(
      (item) => String(item.status).toLowerCase() === "low_stock",
    ).length,
    outOfStockItems: items.filter(
      (item) => String(item.status).toLowerCase() === "out_of_stock",
    ).length,
    totalValue: items.reduce(
      (total, item) => total + safeNumber(item.stockValue),
      0,
    ),
  };

  const summaryBlocks = [
    {
      range: "A4:C5",
      label: "Stock items",
      value: calculatedSummary.totalItems,
      fill: COLOURS.purpleLight,
      font: COLOURS.purple,
      numberFormat: "0",
    },
    {
      range: "D4:F5",
      label: "Total units",
      value: calculatedSummary.totalUnits,
      fill: COLOURS.blueLight,
      font: COLOURS.blue,
      numberFormat: "0",
    },
    {
      range: "G4:I5",
      label: "Low stock",
      value: calculatedSummary.lowStockItems,
      fill: COLOURS.amberLight,
      font: COLOURS.amber,
      numberFormat: "0",
    },
    {
      range: "J4:L5",
      label: "Out of stock",
      value: calculatedSummary.outOfStockItems,
      fill: COLOURS.redLight,
      font: COLOURS.red,
      numberFormat: "0",
    },
    {
      range: "M4:O5",
      label: "Stock value",
      value: calculatedSummary.totalValue,
      fill: COLOURS.greenLight,
      font: COLOURS.green,
      numberFormat: '£#,##0.00;[Red]-£#,##0.00',
    },
  ];

  for (const block of summaryBlocks) {
    sheet.mergeCells(block.range);
    const startCell = block.range.split(":")[0];
    const cell = sheet.getCell(startCell);

    cell.value = {
      richText: [
        {
          text: `${block.label}\n`,
          font: {
            name: "Aptos",
            size: 9,
            bold: true,
            color: { argb: COLOURS.muted },
          },
        },
        {
          text:
            typeof block.value === "number"
              ? block.value.toLocaleString("en-GB")
              : String(block.value),
          font: {
            name: "Aptos Display",
            size: 18,
            bold: true,
            color: { argb: block.font },
          },
        },
      ],
    };

    if (block.label === "Stock value") {
      cell.value = calculatedSummary.totalValue;
      cell.numFmt = block.numberFormat;
      cell.font = {
        name: "Aptos Display",
        size: 18,
        bold: true,
        color: { argb: block.font },
      };
    }

    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: block.fill },
    };
    cell.alignment = {
      vertical: "middle",
      horizontal: "center",
      wrapText: true,
    };
    cell.border = {
      top: { style: "thin", color: { argb: COLOURS.border } },
      left: { style: "thin", color: { argb: COLOURS.border } },
      bottom: { style: "thin", color: { argb: COLOURS.border } },
      right: { style: "thin", color: { argb: COLOURS.border } },
    };
  }

  sheet.getRow(4).height = 26;
  sheet.getRow(5).height = 26;

  const headers = [
    "Item name",
    "SKU",
    "Barcode",
    "Category",
    "Location",
    "Supplier",
    "Quantity",
    "Reorder level",
    "Target level",
    "Unit cost",
    "Sale price",
    "Stock value",
    "Status",
    "Last updated",
    "Updated by",
  ];

  const headerRowNumber = 7;
  const headerRow = sheet.getRow(headerRowNumber);
  headerRow.values = headers;
  headerRow.height = 30;

  headerRow.eachCell((cell) => {
    cell.font = {
      name: "Aptos",
      size: 10,
      bold: true,
      color: { argb: COLOURS.white },
    };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: COLOURS.slate },
    };
    cell.alignment = {
      vertical: "middle",
      horizontal: "center",
      wrapText: true,
    };
    cell.border = {
      top: { style: "thin", color: { argb: COLOURS.border } },
      left: { style: "thin", color: { argb: COLOURS.border } },
      bottom: { style: "thin", color: { argb: COLOURS.border } },
      right: { style: "thin", color: { argb: COLOURS.border } },
    };
  });

  const firstDataRow = headerRowNumber + 1;

  items.forEach((item, index) => {
    const rowNumber = firstDataRow + index;
    const row = sheet.getRow(rowNumber);

    row.values = [
      item.name,
      item.sku,
      item.barcode || "",
      item.category || "Uncategorised",
      item.location || "Not set",
      item.supplier || "Not assigned",
      safeNumber(item.quantity),
      safeNumber(item.reorderLevel),
      item.targetLevel === null || item.targetLevel === undefined
        ? null
        : safeNumber(item.targetLevel),
      item.unitCost === null || item.unitCost === undefined
        ? null
        : safeNumber(item.unitCost),
      item.salePrice === null || item.salePrice === undefined
        ? null
        : safeNumber(item.salePrice),
      item.stockValue === null || item.stockValue === undefined
        ? safeNumber(item.quantity) * safeNumber(item.unitCost)
        : safeNumber(item.stockValue),
      displayStatus(item.status),
      formatDateForCell(item.updatedAt),
      item.updatedByName || "",
    ];

    row.height = 24;

    const alternateFill =
      index % 2 === 0 ? COLOURS.white : "FFF8FAFC";

    row.eachCell({ includeEmpty: true }, (cell) => {
      cell.font = {
        name: "Aptos",
        size: 10,
        color: { argb: COLOURS.text },
      };
      cell.fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: { argb: alternateFill },
      };
      cell.alignment = {
        vertical: "middle",
        horizontal: "left",
        wrapText: true,
      };
      cell.border = {
        top: { style: "hair", color: { argb: COLOURS.border } },
        left: { style: "hair", color: { argb: COLOURS.border } },
        bottom: { style: "hair", color: { argb: COLOURS.border } },
        right: { style: "hair", color: { argb: COLOURS.border } },
      };
    });

    for (const column of [7, 8, 9]) {
      row.getCell(column).alignment = {
        vertical: "middle",
        horizontal: "center",
      };
      row.getCell(column).numFmt = "0";
    }

    for (const column of [10, 11, 12]) {
      row.getCell(column).alignment = {
        vertical: "middle",
        horizontal: "right",
      };
      row.getCell(column).numFmt = '£#,##0.00;[Red]-£#,##0.00';
    }

    row.getCell(14).numFmt = "dd mmm yyyy, hh:mm";
    row.getCell(14).alignment = {
      vertical: "middle",
      horizontal: "center",
    };

    const statusCell = row.getCell(13);
    const style = statusStyle(item.status);
    statusCell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: style.fill },
    };
    statusCell.font = {
      name: "Aptos",
      size: 10,
      bold: true,
      color: { argb: style.font },
    };
    statusCell.alignment = {
      vertical: "middle",
      horizontal: "center",
    };

    if (safeNumber(item.quantity) <= 0) {
      row.getCell(7).font = {
        name: "Aptos",
        size: 10,
        bold: true,
        color: { argb: COLOURS.red },
      };
    } else if (
      safeNumber(item.quantity) <= safeNumber(item.reorderLevel)
    ) {
      row.getCell(7).font = {
        name: "Aptos",
        size: 10,
        bold: true,
        color: { argb: COLOURS.amber },
      };
    }

    row.getCell(1).font = {
      name: "Aptos",
      size: 10,
      bold: true,
      color: { argb: COLOURS.navy },
    };
  });

  const lastDataRow = firstDataRow + items.length - 1;

  sheet.autoFilter = {
    from: { row: headerRowNumber, column: 1 },
    to: { row: lastDataRow, column: headers.length },
  };

  sheet.getColumn(1).width = 28;
  sheet.getColumn(2).width = 18;
  sheet.getColumn(3).width = 18;
  sheet.getColumn(4).width = 20;
  sheet.getColumn(5).width = 22;
  sheet.getColumn(6).width = 24;
  sheet.getColumn(7).width = 12;
  sheet.getColumn(8).width = 14;
  sheet.getColumn(9).width = 14;
  sheet.getColumn(10).width = 14;
  sheet.getColumn(11).width = 14;
  sheet.getColumn(12).width = 15;
  sheet.getColumn(13).width = 16;
  sheet.getColumn(14).width = 22;
  sheet.getColumn(15).width = 22;

  sheet.pageSetup.printTitlesRow = "1:7";
  sheet.pageSetup.printArea = `A1:O${lastDataRow}`;

  sheet.headerFooter.oddHeader =
    '&L&B"Burton Pride Stock Control"&RInventory Report';
  sheet.headerFooter.oddFooter =
    '&LGenerated by Burton Pride Stock Control&CPage &P of &N&R&D &T';

  const workbookBuffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([workbookBuffer as BlobPart], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });
  const downloadUrl = URL.createObjectURL(blob);
  const anchor = document.createElement("a");

  anchor.href = downloadUrl;
  anchor.download = createDownloadName(fileName);

  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();

  URL.revokeObjectURL(downloadUrl);
}
