import ExcelJS from "exceljs";

import { supabaseAdmin } from "@/lib/supabase/supabaseAdmin";
import {
  applyEventAuditFilters,
  createEventAuditLog,
  eventAuditApiError,
  maskAuditRowForActor,
  parseEventAuditFilters,
  requireEventAuditPermission,
  resolveAuditEventScope,
} from "@/lib/event-hub-app/event-audit/index";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function cellText(value: unknown) {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value;
  return JSON.stringify(value);
}

export async function POST(request: Request) {
  try {
    const actor = await requireEventAuditPermission("event_audit:export");
    const body = await request.json().catch(() => ({}));
    const filterUrl = new URL(request.url);

    for (const [key, value] of Object.entries(body?.filters || {})) {
      if (value === null || value === undefined || value === "") continue;
      filterUrl.searchParams.set(
        key,
        Array.isArray(value) ? value.join(",") : String(value),
      );
    }

    const filters = parseEventAuditFilters(filterUrl);
    filters.page = 1;
    filters.pageSize = 200;
    const eventScope = await resolveAuditEventScope(actor, filters.eventId);

    let query = supabaseAdmin.from("event_audit_logs").select("*");
    query = applyEventAuditFilters(query, filters, eventScope, actor)
      .order(filters.sortField, { ascending: filters.sortDirection === "asc" })
      .limit(10_000);

    const { data, error } = await query;
    if (error) throw error;

    const logs = (data || []).map((row) => maskAuditRowForActor(row, actor));
    const workbook = new ExcelJS.Workbook();
    workbook.creator = "Burton Pride C.I.C.";
    workbook.company = "Burton Pride C.I.C.";
    workbook.subject = "Event Hub Audit Log";
    workbook.created = new Date();

    const summary = workbook.addWorksheet("Export Summary", {
      views: [{ showGridLines: false }],
    });
    summary.columns = [{ width: 28 }, { width: 70 }];
    summary.mergeCells("A1:B1");
    summary.getCell("A1").value = "Burton Pride C.I.C. - Event Hub Audit Log";
    summary.getCell("A1").font = { bold: true, size: 20, color: { argb: "FFFFFFFF" } };
    summary.getCell("A1").fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF5B2A86" } };
    summary.getCell("A1").alignment = { vertical: "middle", horizontal: "center" };
    summary.getRow(1).height = 36;
    summary.addRow(["Generated", new Date().toLocaleString("en-GB")]);
    summary.addRow(["Generated by", `${actor.name}${actor.email ? ` (${actor.email})` : ""}`]);
    summary.addRow(["Rows", logs.length]);
    summary.addRow(["Event scope", eventScope || "All permitted events"]);
    summary.addRow(["Search", filters.q || "None"]);
    summary.addRow(["Area", filters.area || "All"]);
    summary.addRow(["Status", filters.status.join(", ") || "All"]);
    summary.addRow(["Risk", filters.risk.join(", ") || "All"]);
    summary.addRow(["Date from", filters.dateFrom || "Not set"]);
    summary.addRow(["Date to", filters.dateTo || "Not set"]);
    summary.eachRow((row, rowNumber) => {
      if (rowNumber > 1) {
        row.getCell(1).font = { bold: true };
        row.alignment = { vertical: "top", wrapText: true };
      }
    });

    const sheet = workbook.addWorksheet("Audit Events", {
      views: [{ state: "frozen", ySplit: 1, showGridLines: false }],
      pageSetup: {
        orientation: "landscape",
        fitToPage: true,
        fitToWidth: 1,
        fitToHeight: 0,
      },
    });

    sheet.columns = [
      { header: "Date and time", key: "created_at", width: 23 },
      { header: "Admin", key: "admin_name", width: 24 },
      { header: "Email", key: "admin_email", width: 32 },
      { header: "Role", key: "admin_role", width: 18 },
      { header: "Action", key: "action_label", width: 30 },
      { header: "Technical action", key: "action", width: 30 },
      { header: "Area", key: "area", width: 18 },
      { header: "Record", key: "record_title", width: 38 },
      { header: "Record type", key: "record_type", width: 20 },
      { header: "Status", key: "status", width: 18 },
      { header: "Risk", key: "risk_level", width: 14 },
      { header: "Summary", key: "summary", width: 45 },
      { header: "Reason", key: "reason", width: 40 },
      { header: "Changed fields", key: "changed_fields", width: 55 },
      { header: "Route", key: "route", width: 45 },
      { header: "Method", key: "http_method", width: 12 },
      { header: "Response", key: "response_status", width: 12 },
      { header: "Request ID", key: "request_id", width: 34 },
      { header: "Browser", key: "browser", width: 16 },
      { header: "Device", key: "device_type", width: 15 },
      { header: "IP", key: "ip_address", width: 20 },
      { header: "Audit ID", key: "id", width: 38 },
    ];

    const header = sheet.getRow(1);
    header.height = 30;
    header.font = { bold: true, color: { argb: "FFFFFFFF" } };
    header.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F766E" } };
    header.alignment = { vertical: "middle", horizontal: "center", wrapText: true };

    for (const log of logs) {
      sheet.addRow({
        ...log,
        created_at: log.created_at ? new Date(log.created_at) : "",
        changed_fields: cellText(log.changed_fields),
      });
    }

    sheet.getColumn("created_at").numFmt = "dd mmm yyyy hh:mm:ss";
    sheet.autoFilter = { from: "A1", to: "V1" };
    sheet.eachRow((row, index) => {
      if (index > 1) {
        row.alignment = { vertical: "top", wrapText: true };
        if (index % 2 === 0) {
          row.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF3F4F6" } };
        }
      }
    });

    const exportLog = await createEventAuditLog({
      eventId: eventScope === "system" ? null : eventScope,
      actor,
      action: "export.created",
      area: "exports",
      status: "success",
      riskLevel: logs.some((log) => log.is_confidential) ? "high" : "medium",
      summary: `Exported ${logs.length} Event Hub audit events to XLSX.`,
      metadata: {
        row_count: logs.length,
        format: "xlsx",
        filters: body?.filters || {},
      },
      request,
      responseStatus: 200,
      isConfidential: logs.some((log) => log.is_confidential),
      requiresReview: logs.length >= 1000,
      strict: true,
    });

    summary.addRow(["Export audit ID", exportLog?.id || "Unavailable"]);

    const output = await workbook.xlsx.writeBuffer();
    const date = new Date().toISOString().slice(0, 10);

    return new Response(Buffer.from(output), {
      status: 200,
      headers: {
        "Content-Type":
          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "Content-Disposition": `attachment; filename="burton-pride-event-audit-${date}.xlsx"`,
        "Cache-Control": "no-store",
        "X-Robots-Tag": "noindex, noarchive",
      },
    });
  } catch (error) {
    return eventAuditApiError(error);
  }
}
