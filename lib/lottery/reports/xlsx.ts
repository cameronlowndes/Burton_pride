import ExcelJS from "exceljs";

export type ReportSheetColumn = {
  header: string;
  key: string;
  width?: number;
  style?: "text" | "money" | "number" | "date" | "datetime" | "boolean";
};

export type ReportSheet = {
  name: string;
  title: string;
  subtitle?: string;
  columns: ReportSheetColumn[];
  rows: Array<Record<string, unknown>>;
};

export type ReportWorkbookOptions = {
  title: string;
  subtitle?: string;
  generatedBy?: string | null;
  lotteryTitle?: string | null;
  periodLabel?: string | null;
  sheets: ReportSheet[];
};

const BRAND = {
  navy: "FF121426",
  navy2: "FF1B1E35",
  purple: "FF7C3AED",
  pink: "FFEC4899",
  blue: "FF3B82F6",
  white: "FFFFFFFF",
  softWhite: "FFF4F4F7",
  muted: "FFB9BBC8",
  lightBorder: "FFD9D9E3",
  green: "FF059669",
  amber: "FFD97706",
  red: "FFDC2626",
};

const thinBorder: Partial<ExcelJS.Borders> = {
  top: { style: "thin", color: { argb: BRAND.lightBorder } },
  left: { style: "thin", color: { argb: BRAND.lightBorder } },
  bottom: { style: "thin", color: { argb: BRAND.lightBorder } },
  right: { style: "thin", color: { argb: BRAND.lightBorder } },
};

function sanitizeSheetName(name: string) {
  return name.replace(/[\\/*?:[\]]/g, " ").slice(0, 31) || "Report";
}

function safeFilenamePart(value: string) {
  return value
    .trim()
    .replace(/[^a-z0-9-_]+/gi, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function asDate(value: unknown): Date | null {
  if (!value) return null;
  const date = value instanceof Date ? value : new Date(String(value));
  return Number.isNaN(date.getTime()) ? null : date;
}

function applyCellValue(
  cell: ExcelJS.Cell,
  value: unknown,
  style: ReportSheetColumn["style"],
) {
  if (value === null || value === undefined || value === "") {
    cell.value = "";
    return;
  }

  switch (style) {
    case "money":
      cell.value = Number(value || 0);
      cell.numFmt = '£#,##0.00;[Red]-£#,##0.00';
      break;
    case "number":
      cell.value = Number(value || 0);
      cell.numFmt = "#,##0";
      break;
    case "date": {
      const date = asDate(value);
      cell.value = date || String(value);
      if (date) cell.numFmt = "dd mmm yyyy";
      break;
    }
    case "datetime": {
      const date = asDate(value);
      cell.value = date || String(value);
      if (date) cell.numFmt = "dd mmm yyyy hh:mm";
      break;
    }
    case "boolean":
      cell.value = Boolean(value) ? "Yes" : "No";
      break;
    default:
      cell.value =
        typeof value === "object" ? JSON.stringify(value) : String(value);
  }
}

function styleWorkbookSheet(
  worksheet: ExcelJS.Worksheet,
  sheet: ReportSheet,
  options: ReportWorkbookOptions,
) {
  const columnCount = Math.max(1, sheet.columns.length);
  const lastColumn = worksheet.getColumn(columnCount).letter;

  worksheet.views = [
    {
      state: "frozen",
      xSplit: 0,
      ySplit: 7,
      showGridLines: false,
    },
  ];

  worksheet.properties.defaultRowHeight = 20;
  worksheet.pageSetup = {
    orientation: columnCount > 8 ? "landscape" : "portrait",
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    margins: {
      left: 0.35,
      right: 0.35,
      top: 0.5,
      bottom: 0.5,
      header: 0.2,
      footer: 0.2,
    },
  };

  worksheet.mergeCells(`A1:${lastColumn}1`);
  const titleCell = worksheet.getCell("A1");
  titleCell.value = options.title;
  titleCell.font = {
    name: "Aptos Display",
    size: 20,
    bold: true,
    color: { argb: BRAND.white },
  };
  titleCell.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: BRAND.navy },
  };
  titleCell.alignment = { vertical: "middle", horizontal: "left" };
  worksheet.getRow(1).height = 34;

  worksheet.mergeCells(`A2:${lastColumn}2`);
  const subtitleCell = worksheet.getCell("A2");
  subtitleCell.value = sheet.title;
  subtitleCell.font = {
    name: "Aptos",
    size: 13,
    bold: true,
    color: { argb: BRAND.purple },
  };
  subtitleCell.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "FFF3F0FF" },
  };
  worksheet.getRow(2).height = 26;

  worksheet.mergeCells(`A3:${lastColumn}3`);
  const detailCell = worksheet.getCell("A3");
  detailCell.value =
    sheet.subtitle ||
    options.subtitle ||
    "Burton Pride Lottery Management System";
  detailCell.font = {
    name: "Aptos",
    size: 10,
    color: { argb: "FF525466" },
  };
  detailCell.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: BRAND.softWhite },
  };

  worksheet.getCell("A4").value = "Generated";
  worksheet.getCell("B4").value = new Date();
  worksheet.getCell("B4").numFmt = "dd mmm yyyy hh:mm";
  worksheet.getCell("D4").value = "Generated by";
  worksheet.getCell("E4").value = options.generatedBy || "Burton Pride Admin Portal";

  worksheet.getCell("A5").value = "Lottery";
  worksheet.getCell("B5").value = options.lotteryTitle || "All lotteries";
  worksheet.getCell("D5").value = "Period";
  worksheet.getCell("E5").value = options.periodLabel || "All available data";

  for (const address of ["A4", "D4", "A5", "D5"]) {
    const cell = worksheet.getCell(address);
    cell.font = { bold: true, color: { argb: "FF5B5D6B" } };
  }

  for (const address of ["B4", "E4", "B5", "E5"]) {
    worksheet.getCell(address).font = { color: { argb: "FF1F2130" } };
  }

  const headerRow = worksheet.getRow(7);
  headerRow.values = sheet.columns.map((column) => column.header);
  headerRow.height = 27;
  headerRow.eachCell((cell) => {
    cell.font = {
      name: "Aptos",
      bold: true,
      color: { argb: BRAND.white },
    };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: BRAND.navy2 },
    };
    cell.border = thinBorder;
    cell.alignment = {
      vertical: "middle",
      horizontal: "left",
      wrapText: true,
    };
  });

  sheet.columns.forEach((column, index) => {
    worksheet.getColumn(index + 1).width = Math.min(
      Math.max(column.width || 16, 10),
      38,
    );
  });

  sheet.rows.forEach((record, index) => {
    const excelRow = worksheet.getRow(8 + index);

    sheet.columns.forEach((column, columnIndex) => {
      const cell = excelRow.getCell(columnIndex + 1);
      applyCellValue(cell, record[column.key], column.style);
      cell.border = thinBorder;
      cell.alignment = {
        vertical: "top",
        horizontal:
          column.style === "money" || column.style === "number"
            ? "right"
            : "left",
        wrapText: true,
      };

      cell.fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: {
          argb: index % 2 === 0 ? BRAND.white : "FFF8F8FB",
        },
      };
    });

    excelRow.height = 22;
  });

  if (sheet.rows.length > 0) {
    worksheet.autoFilter = {
      from: "A7",
      to: `${lastColumn}${7 + sheet.rows.length}`,
    };
  }

  const footerRowNumber = 9 + sheet.rows.length;
  worksheet.mergeCells(`A${footerRowNumber}:${lastColumn}${footerRowNumber}`);
  const footerCell = worksheet.getCell(`A${footerRowNumber}`);
  footerCell.value =
    "Confidential operational report — Burton Pride Lottery Management";
  footerCell.font = {
    italic: true,
    size: 9,
    color: { argb: "FF777986" },
  };
  footerCell.alignment = { horizontal: "left" };

  worksheet.headerFooter.oddFooter =
    "&LBurton Pride Lottery Management&CPage &P of &N&RConfidential";
}

export async function buildStyledXlsx(
  options: ReportWorkbookOptions,
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();

  workbook.creator = "Burton Pride Lottery Management";
  workbook.company = "Burton Pride C.I.C.";
  workbook.subject = options.title;
  workbook.title = options.title;
  workbook.description =
    options.subtitle || "Burton Pride Lottery Management report";
  workbook.created = new Date();
  workbook.modified = new Date();

  for (const sheet of options.sheets) {
    const worksheet = workbook.addWorksheet(sanitizeSheetName(sheet.name), {
      properties: {
        tabColor: { argb: BRAND.purple },
      },
    });

    styleWorkbookSheet(worksheet, sheet, options);
  }

  const arrayBuffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(arrayBuffer);
}

export function xlsxDownloadResponse(
  buffer: Buffer,
  filename: string,
): Response {
  const safeFilename = filename.toLowerCase().endsWith(".xlsx")
    ? filename
    : `${filename}.xlsx`;

  return new Response(new Uint8Array(buffer), {
    status: 200,
    headers: {
      "Content-Type":
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      "Content-Disposition": `attachment; filename="${safeFilename}"`,
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff",
    },
  });
}

export function buildReportFilename(
  type: string,
  lotteryTitle?: string | null,
) {
  const lottery = lotteryTitle
    ? `${safeFilenamePart(lotteryTitle)}-`
    : "";

  return `burton-pride-${lottery}${safeFilenamePart(type)}-${new Date()
    .toISOString()
    .slice(0, 10)}.xlsx`;
}
